create or replace function public.create_booking(
  p_vehicle_id uuid,
  p_pickup_at timestamptz,
  p_dropoff_at timestamptz,
  p_pickup_district text,
  p_pickup_location text,
  p_dropoff_location text,
  p_contact_email text,
  p_contact_phone text,
  p_contact_address text,
  p_payment_method text,
  p_coupon_code text default null,
  p_add_on_codes text[] default '{}'::text[],
  p_business_account_id uuid default null,
  p_mileage_package_km integer default null,
  p_protection_package text default 'standard'
)
returns public.bookings
language plpgsql
security definer
set search_path = ''
as $$
declare
  selected_vehicle public.vehicles;
  created_booking public.bookings;
  price_quote jsonb;
  item jsonb;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  if public.current_app_role() <> 'customer' then
    raise exception 'Only customers can create bookings' using errcode = '42501';
  end if;

  select * into selected_vehicle
  from public.vehicles
  where id = p_vehicle_id
    and deleted_at is null
    and approval_status = 'approved'
  for update;

  if selected_vehicle.id is null then
    raise exception 'Vehicle is not available' using errcode = 'P0002';
  end if;

  price_quote := public.quote_booking(
    p_vehicle_id, p_pickup_at, p_dropoff_at, p_pickup_district, p_pickup_location,
    p_dropoff_location, p_coupon_code, p_add_on_codes, p_business_account_id,
    p_mileage_package_km, p_protection_package
  );

  insert into public.bookings (
    vehicle_id, customer_id, business_account_id, pickup_at, dropoff_at, pickup_district,
    pickup_location, dropoff_location, contact_email, contact_phone, contact_address,
    rental_days, daily_price, delivery_fee, discount, total_price, rental_product,
    protection_package, mileage_package_km, selected_addons, subtotal, add_ons_total,
    one_way_fee, long_term_discount, loyalty_discount, business_discount, deposit_amount
  ) values (
    selected_vehicle.id, (select auth.uid()), p_business_account_id, p_pickup_at, p_dropoff_at,
    p_pickup_district, p_pickup_location, p_dropoff_location, p_contact_email,
    p_contact_phone, p_contact_address, (price_quote ->> 'rental_days')::integer,
    (price_quote ->> 'daily_price')::numeric, (price_quote ->> 'delivery_fee')::numeric,
    (price_quote ->> 'discount')::numeric, (price_quote ->> 'total_price')::numeric,
    price_quote ->> 'rental_product', coalesce(p_protection_package, 'standard'),
    p_mileage_package_km, to_jsonb(coalesce(p_add_on_codes, '{}'::text[])),
    (price_quote ->> 'subtotal')::numeric,
    (price_quote ->> 'add_ons_total')::numeric
      + (price_quote ->> 'protection_fee')::numeric
      + (price_quote ->> 'mileage_fee')::numeric,
    (price_quote ->> 'one_way_fee')::numeric, (price_quote ->> 'long_term_discount')::numeric,
    (price_quote ->> 'loyalty_discount')::numeric, (price_quote ->> 'business_discount')::numeric,
    (price_quote ->> 'deposit_amount')::numeric
  ) returning * into created_booking;

  for item in select * from jsonb_array_elements(price_quote -> 'line_items')
  loop
    insert into public.booking_line_items (booking_id, item_type, code, description, amount)
    values (
      created_booking.id,
      item ->> 'type',
      item ->> 'code',
      item ->> 'description',
      (item ->> 'amount')::numeric
    );
  end loop;

  insert into public.payments (booking_id, provider, amount)
  values (created_booking.id, p_payment_method, created_booking.total_price);

  insert into public.booking_status_history (booking_id, to_status, changed_by)
  values (created_booking.id, created_booking.status, (select auth.uid()));
  return created_booking;
exception
  when exclusion_violation then
    raise exception 'Vehicle is already booked for the selected dates' using errcode = '23P01';
end;
$$;

create or replace function public.modify_own_booking(
  p_booking_id uuid,
  p_pickup_at timestamptz,
  p_dropoff_at timestamptz,
  p_dropoff_location text,
  p_coupon_code text default null,
  p_add_on_codes text[] default '{}'::text[],
  p_mileage_package_km integer default null,
  p_protection_package text default 'standard'
)
returns public.bookings
language plpgsql
security definer
set search_path = ''
as $$
declare
  existing_booking public.bookings;
  updated_booking public.bookings;
  selected_vehicle public.vehicles;
  v_rental_days integer;
  previous_snapshot jsonb;
  new_total numeric(12, 2);
  new_subtotal numeric(12, 2);
  new_delivery_fee numeric(12, 2) := 10000;
  new_one_way_fee numeric(12, 2);
  new_protection_fee numeric(12, 2);
  new_mileage_fee numeric(12, 2);
  new_add_on_total numeric(12, 2);
  new_discount numeric(12, 2);
begin
  select * into existing_booking
  from public.bookings
  where id = p_booking_id and customer_id = (select auth.uid())
  for update;

  if existing_booking.id is null then
    raise exception 'Booking not found' using errcode = 'P0002';
  end if;
  if existing_booking.status not in ('pending', 'confirmed') then
    raise exception 'This booking can no longer be modified' using errcode = 'P0001';
  end if;
  if existing_booking.pickup_at <= now() + interval '4 hours' then
    raise exception 'Bookings can only be modified at least 4 hours before pickup' using errcode = 'P0001';
  end if;
  if p_dropoff_at <= p_pickup_at then
    raise exception 'Drop-off must be later than pickup' using errcode = '22007';
  end if;

  if exists (
    select 1
    from public.bookings booking
    where booking.vehicle_id = existing_booking.vehicle_id
      and booking.id <> existing_booking.id
      and booking.status in ('pending', 'confirmed', 'active')
      and tstzrange(booking.pickup_at, booking.dropoff_at, '[)')
        && tstzrange(p_pickup_at, p_dropoff_at, '[)')
  ) or exists (
    select 1
    from public.fleet_blocks block
    where block.vehicle_id = existing_booking.vehicle_id
      and tstzrange(block.starts_at, block.ends_at, '[)')
        && tstzrange(p_pickup_at, p_dropoff_at, '[)')
  ) then
    raise exception 'Vehicle is already booked or blocked for the selected dates' using errcode = '23P01';
  end if;

  select * into selected_vehicle from public.vehicles where id = existing_booking.vehicle_id;
  v_rental_days := greatest(1, ceil(extract(epoch from (p_dropoff_at - p_pickup_at)) / 86400.0)::integer);
  new_subtotal := selected_vehicle.price_per_day * v_rental_days;
  new_one_way_fee := case when lower(existing_booking.pickup_location) <> lower(coalesce(p_dropoff_location, existing_booking.dropoff_location)) then 25000 else 0 end;
  new_protection_fee := case coalesce(p_protection_package, existing_booking.protection_package)
    when 'plus' then v_rental_days * 15000
    when 'premium' then v_rental_days * 25000
    else 0
  end;
  new_mileage_fee := case
    when coalesce(p_mileage_package_km, 0) >= 2000 then 50000
    when coalesce(p_mileage_package_km, 0) >= 1000 then 25000
    else 0
  end;
  select coalesce(sum(
    case add_on.price_type
      when 'per_day' then add_on.price_amount * v_rental_days
      else add_on.price_amount
    end
  ), 0)
  into new_add_on_total
  from public.booking_add_ons add_on
  where add_on.code = any(coalesce(p_add_on_codes, '{}'::text[]))
    and add_on.applies_to = 'rental'
    and add_on.is_active;
  new_discount := case when upper(coalesce(p_coupon_code, '')) = 'KARIBU10000' then 10000 else 0 end
    + case when v_rental_days >= 90 then new_subtotal * 0.15 when v_rental_days >= 28 then new_subtotal * 0.10 else 0 end;
  new_total := greatest(0, new_subtotal + new_delivery_fee + new_one_way_fee + new_protection_fee + new_mileage_fee + new_add_on_total - new_discount);

  previous_snapshot := jsonb_build_object(
    'pickup_at', existing_booking.pickup_at,
    'dropoff_at', existing_booking.dropoff_at,
    'dropoff_location', existing_booking.dropoff_location,
    'total_price', existing_booking.total_price
  );

  update public.bookings
  set pickup_at = p_pickup_at,
      dropoff_at = p_dropoff_at,
      dropoff_location = coalesce(p_dropoff_location, dropoff_location),
      rental_days = v_rental_days,
      rental_product = case when v_rental_days >= 28 then 'long_term' else 'short_term' end,
      protection_package = coalesce(p_protection_package, protection_package),
      mileage_package_km = p_mileage_package_km,
      selected_addons = to_jsonb(coalesce(p_add_on_codes, '{}'::text[])),
      subtotal = new_subtotal,
      add_ons_total = new_add_on_total + new_protection_fee + new_mileage_fee,
      one_way_fee = new_one_way_fee,
      long_term_discount = case when v_rental_days >= 90 then new_subtotal * 0.15 when v_rental_days >= 28 then new_subtotal * 0.10 else 0 end,
      discount = new_discount,
      total_price = new_total
  where id = existing_booking.id
  returning * into updated_booking;

  insert into public.booking_amendments (booking_id, changed_by, previous_values, new_values, price_delta)
  values (
    updated_booking.id,
    (select auth.uid()),
    previous_snapshot,
    jsonb_build_object(
      'pickup_at', updated_booking.pickup_at,
      'dropoff_at', updated_booking.dropoff_at,
      'dropoff_location', updated_booking.dropoff_location,
      'total_price', updated_booking.total_price
    ),
    updated_booking.total_price - existing_booking.total_price
  );

  return updated_booking;
end;
$$;

create or replace function public.cancel_own_booking(p_booking_id uuid)
returns public.bookings
language plpgsql
security definer
set search_path = ''
as $$
declare
  existing_booking public.bookings;
  updated_booking public.bookings;
  fee numeric(12, 2);
begin
  select * into existing_booking from public.bookings
  where id = p_booking_id and customer_id = (select auth.uid()) for update;
  if existing_booking.id is null then
    raise exception 'Booking not found' using errcode = 'P0002';
  end if;
  if existing_booking.status not in ('pending', 'confirmed') then
    raise exception 'This booking can no longer be cancelled' using errcode = 'P0001';
  end if;

  fee := case
    when existing_booking.pickup_at <= now() + interval '24 hours' then round(existing_booking.total_price * 0.20, 2)
    when existing_booking.pickup_at <= now() + interval '48 hours' then round(existing_booking.total_price * 0.10, 2)
    else 0
  end;

  update public.bookings
  set status = 'cancelled', cancelled_at = now(), cancellation_fee = fee
  where id = p_booking_id returning * into updated_booking;

  if fee > 0 then
    insert into public.booking_line_items (booking_id, item_type, code, description, amount)
    values (updated_booking.id, 'cancellation', 'cancellation_fee', 'Cancellation fee', fee);
  end if;

  insert into public.booking_status_history (booking_id, from_status, to_status, changed_by)
  values (updated_booking.id, existing_booking.status, 'cancelled', (select auth.uid()));
  return updated_booking;
end;
$$;

create or replace function public.set_booking_status(
  p_booking_id uuid,
  p_status public.booking_status
)
returns public.bookings
language plpgsql
security definer
set search_path = ''
as $$
declare
  existing_booking public.bookings;
  updated_booking public.bookings;
  caller_role public.app_role;
  earned_points integer;
  new_status_points integer;
begin
  caller_role := public.current_app_role();
  select * into existing_booking from public.bookings where id = p_booking_id for update;
  if existing_booking.id is null then
    raise exception 'Booking not found' using errcode = 'P0002';
  end if;
  if caller_role <> 'admin' and not exists (
    select 1 from public.vehicles
    where id = existing_booking.vehicle_id and owner_id = (select auth.uid())
  ) then
    raise exception 'Not allowed to update this booking' using errcode = '42501';
  end if;

  update public.bookings
  set status = p_status,
      cancelled_at = case when p_status = 'cancelled' then now() else cancelled_at end
  where id = p_booking_id
  returning * into updated_booking;

  insert into public.booking_status_history (booking_id, from_status, to_status, changed_by)
  values (updated_booking.id, existing_booking.status, updated_booking.status, (select auth.uid()));

  if p_status = 'completed' and existing_booking.status <> 'completed' and updated_booking.customer_id is not null then
    earned_points := floor(updated_booking.total_price / 10000)::integer;
    insert into public.loyalty_accounts (customer_id, rental_points, status_points, lifetime_spend)
    values (updated_booking.customer_id, greatest(earned_points, 0), greatest(earned_points, 0), updated_booking.total_price)
    on conflict (customer_id) do update
    set rental_points = public.loyalty_accounts.rental_points + greatest(earned_points, 0),
        status_points = public.loyalty_accounts.status_points + greatest(earned_points, 0),
        lifetime_spend = public.loyalty_accounts.lifetime_spend + updated_booking.total_price,
        updated_at = now();

    insert into public.loyalty_transactions (customer_id, booking_id, points, transaction_type, description)
    values (updated_booking.customer_id, updated_booking.id, greatest(earned_points, 0), 'earned', 'Completed rental reward');

    select status_points into new_status_points
    from public.loyalty_accounts
    where customer_id = updated_booking.customer_id;

    update public.loyalty_accounts
    set tier = case
        when new_status_points >= 6000 then 'diamond'
        when new_status_points >= 4000 then 'platinum'
        when new_status_points >= 2000 then 'gold'
        else 'silver'
      end,
      tier_expires_on = (date_trunc('year', now()) + interval '2 years' - interval '1 day')::date
    where customer_id = updated_booking.customer_id;
  end if;

  return updated_booking;
end;
$$;

