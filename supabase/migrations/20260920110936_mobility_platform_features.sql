    p_destination_location, p_hours, coalesce(p_passenger_count, 1), coalesce(p_luggage_count, 0),
    coalesce(p_ride_class, 'standard'), round(base_price * class_multiplier, 2),
    p_contact_email, p_contact_phone
  )
  returning * into result;

  return result;
end;
