create or replace function public.ensure_loyalty_account(p_customer_id uuid)
returns public.loyalty_accounts
language plpgsql
security definer
set search_path = ''
as $$
declare
  result public.loyalty_accounts;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  if p_customer_id <> (select auth.uid()) and not public.is_admin() then
    raise exception 'Not allowed to manage this loyalty account' using errcode = '42501';
  end if;

  insert into public.loyalty_accounts (customer_id)
  values (p_customer_id)
  on conflict (customer_id) do nothing;

  select * into result
  from public.loyalty_accounts
  where customer_id = p_customer_id;

  return result;
end;
$$;

