create or replace function public.quote_booking(
  p_vehicle_id uuid,
  p_pickup_at timestamptz,
  p_dropoff_at timestamptz,
  p_pickup_district text,
  p_pickup_location text,
  p_dropoff_location text,
  p_coupon_code text default null,
  p_add_on_codes text[] default '{}'::text[],
  p_business_account_id uuid default null,
  p_mileage_package_km integer default null,
  p_protection_package text default 'standard'
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  selected_vehicle public.vehicles;
  loyalty public.loyalty_accounts;
  rental_days integer;
  rental_product text;
  rent_subtotal numeric(12, 2);
  delivery_fee numeric(12, 2) := 10000;
  one_way_fee numeric(12, 2) := 0;
  protection_fee numeric(12, 2) := 0;
  mileage_fee numeric(12, 2) := 0;
  add_on_total numeric(12, 2) := 0;
  gross_total numeric(12, 2);
  coupon_discount numeric(12, 2) := 0;
  long_discount numeric(12, 2) := 0;
  member_discount numeric(12, 2) := 0;
  corporate_discount numeric(12, 2) := 0;
  discount_total numeric(12, 2);
  final_total numeric(12, 2);
  deposit numeric(12, 2);
  line_items jsonb := '[]'::jsonb;
  current_user_id uuid := (select auth.uid());
begin
  if p_dropoff_at <= p_pickup_at then
    raise exception 'Drop-off must be later than pickup' using errcode = '22007';
  end if;
  if coalesce(p_protection_package, 'standard') not in ('standard', 'plus', 'premium') then
    raise exception 'Unsupported protection package' using errcode = '22023';
  end if;

  select * into selected_vehicle
  from public.vehicles
  where id = p_vehicle_id
    and deleted_at is null
    and approval_status = 'approved';

  if selected_vehicle.id is null then
    raise exception 'Vehicle is not available' using errcode = 'P0002';
  end if;

  if exists (
    select 1
    from public.bookings booking
    where booking.vehicle_id = selected_vehicle.id
      and booking.status in ('pending', 'confirmed', 'active')
      and tstzrange(booking.pickup_at, booking.dropoff_at, '[)')
        && tstzrange(p_pickup_at, p_dropoff_at, '[)')
  ) or exists (
    select 1
    from public.fleet_blocks block
    where block.vehicle_id = selected_vehicle.id
      and tstzrange(block.starts_at, block.ends_at, '[)')
        && tstzrange(p_pickup_at, p_dropoff_at, '[)')
  ) then
    raise exception 'Vehicle is already booked or blocked for the selected dates' using errcode = '23P01';
  end if;

  rental_days := greatest(1, ceil(extract(epoch from (p_dropoff_at - p_pickup_at)) / 86400.0)::integer);
  rental_product := case when rental_days >= 28 then 'long_term' else 'short_term' end;
  rent_subtotal := selected_vehicle.price_per_day * rental_days;
  one_way_fee := case when lower(coalesce(p_pickup_location, '')) <> lower(coalesce(p_dropoff_location, '')) then 25000 else 0 end;
  protection_fee := case coalesce(p_protection_package, 'standard')
    when 'plus' then rental_days * 15000
    when 'premium' then rental_days * 25000
    else 0
  end;
  mileage_fee := case
    when coalesce(p_mileage_package_km, 0) >= 2000 then 50000
    when coalesce(p_mileage_package_km, 0) >= 1000 then 25000
    else 0
  end;

  select coalesce(sum(
    case add_on.price_type
      when 'per_day' then add_on.price_amount * rental_days
      else add_on.price_amount
    end
  ), 0)
  into add_on_total
  from public.booking_add_ons add_on
  where add_on.code = any(coalesce(p_add_on_codes, '{}'::text[]))
    and add_on.applies_to = 'rental'
    and add_on.is_active;

  coupon_discount := case when upper(coalesce(p_coupon_code, '')) = 'KARIBU10000' then 10000 else 0 end;
  long_discount := case
    when rental_days >= 90 then rent_subtotal * 0.15
    when rental_days >= 28 then rent_subtotal * 0.10
    else 0
  end;

  if current_user_id is not null and p_business_account_id is null then
    select * into loyalty
    from public.loyalty_accounts
    where customer_id = current_user_id;

    member_discount := case loyalty.tier
      when 'diamond' then rent_subtotal * 0.10
      when 'platinum' then rent_subtotal * 0.08
      when 'gold' then rent_subtotal * 0.05
      else rent_subtotal * 0.02
    end;
  end if;

  if p_business_account_id is not null then
    if not public.is_business_member(p_business_account_id) then
      raise exception 'Not allowed to use this business account' using errcode = '42501';
    end if;

    select rent_subtotal * (account.discount_percent / 100.0)
    into corporate_discount
    from public.business_accounts account
    where account.id = p_business_account_id and account.status = 'approved';
  end if;

  gross_total := rent_subtotal + delivery_fee + one_way_fee + protection_fee + mileage_fee + add_on_total;
  discount_total := least(gross_total, coupon_discount + long_discount + member_discount + coalesce(corporate_discount, 0));
  final_total := greatest(0, gross_total - discount_total);
  deposit := greatest(50000, round(final_total * 0.15, 2));

  line_items := line_items || jsonb_build_array(jsonb_build_object('type', 'rent', 'code', 'daily_rent', 'description', 'Rental days', 'amount', rent_subtotal));
  line_items := line_items || jsonb_build_array(jsonb_build_object('type', 'fee', 'code', 'pickup_support', 'description', 'Pickup support', 'amount', delivery_fee));
  if one_way_fee > 0 then
    line_items := line_items || jsonb_build_array(jsonb_build_object('type', 'fee', 'code', 'one_way', 'description', 'Different return location', 'amount', one_way_fee));
  end if;
  if protection_fee > 0 then
    line_items := line_items || jsonb_build_array(jsonb_build_object('type', 'addon', 'code', 'protection', 'description', initcap(p_protection_package) || ' protection', 'amount', protection_fee));
  end if;
  if mileage_fee > 0 then
    line_items := line_items || jsonb_build_array(jsonb_build_object('type', 'addon', 'code', 'mileage_package', 'description', 'Mileage package', 'amount', mileage_fee));
  end if;
  if add_on_total > 0 then
    line_items := line_items || (
      select coalesce(jsonb_agg(jsonb_build_object(
        'type', 'addon',
        'code', add_on.code,
        'description', add_on.name,
        'amount', case add_on.price_type when 'per_day' then add_on.price_amount * rental_days else add_on.price_amount end
      )), '[]'::jsonb)
      from public.booking_add_ons add_on
      where add_on.code = any(coalesce(p_add_on_codes, '{}'::text[]))
        and add_on.applies_to = 'rental'
        and add_on.is_active
    );
  end if;
  if discount_total > 0 then
    line_items := line_items || jsonb_build_array(jsonb_build_object('type', 'discount', 'code', 'discounts', 'description', 'Applied discounts', 'amount', -discount_total));
  end if;
  line_items := line_items || jsonb_build_array(jsonb_build_object('type', 'deposit', 'code', 'security_deposit', 'description', 'Refundable security deposit estimate', 'amount', deposit));

  return jsonb_build_object(
    'vehicle_id', selected_vehicle.id,
    'rental_days', rental_days,
    'rental_product', rental_product,
    'daily_price', selected_vehicle.price_per_day,
    'subtotal', rent_subtotal,
    'delivery_fee', delivery_fee,
    'one_way_fee', one_way_fee,
    'protection_fee', protection_fee,
    'mileage_fee', mileage_fee,
    'add_ons_total', add_on_total,
    'coupon_discount', coupon_discount,
    'long_term_discount', long_discount,
    'loyalty_discount', member_discount,
    'business_discount', coalesce(corporate_discount, 0),
    'discount', discount_total,
    'total_price', final_total,
    'deposit_amount', deposit,
    'currency', 'TZS',
    'line_items', line_items
  );
end;
$$;

create or replace function public.search_available_vehicles(
  p_pickup_at timestamptz,
  p_dropoff_at timestamptz,
  p_district text default null,
  p_location text default null
)
returns setof public.vehicles
language sql
stable
security definer
set search_path = ''
as $$
  select vehicle.* from public.vehicles as vehicle
  where vehicle.deleted_at is null
    and vehicle.approval_status = 'approved'
    and p_dropoff_at > p_pickup_at
    and (p_district is null or vehicle.district = p_district)
    and (p_location is null or vehicle.location = p_location)
    and not exists (
      select 1 from public.bookings as booking
      where booking.vehicle_id = vehicle.id
        and booking.status in ('pending', 'confirmed', 'active')
        and tstzrange(booking.pickup_at, booking.dropoff_at, '[)')
          && tstzrange(p_pickup_at, p_dropoff_at, '[)')
    )
    and not exists (
      select 1 from public.fleet_blocks as block
      where block.vehicle_id = vehicle.id
        and tstzrange(block.starts_at, block.ends_at, '[)')
          && tstzrange(p_pickup_at, p_dropoff_at, '[)')
    )
  order by vehicle.price_per_day, vehicle.created_at desc;
$$;

