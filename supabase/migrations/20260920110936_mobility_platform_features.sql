    when 'first' then 2.2
    when 'business' then 1.6
    when 'xl' then 1.8
    when 'green' then 1.3
    else 1
  end;

  insert into public.ride_bookings (
    customer_id, business_account_id, service_type, pickup_at, pickup_location,
    destination_location, hours, passenger_count, luggage_count, ride_class,
