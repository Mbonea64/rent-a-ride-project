create or replace function public.register_as_vendor()
returns public.profiles
language plpgsql
security definer
set search_path = ''
as $$
declare
  result public.profiles;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  update public.profiles set role = 'vendor'
  where id = (select auth.uid()) and role = 'customer'
  returning * into result;

  if result.id is null then
    select * into result from public.profiles where id = (select auth.uid());
  end if;
  return result;
end;
$$;

create or replace function public.search_available_vehicles(
  p_pickup_at timestamptz,
  p_dropoff_at timestamptz,
  p_district text default null,
  p_location text default null
)
returns setof public.vehicles
language sql
stable
security definer
set search_path = ''
as $$
  select vehicle.* from public.vehicles as vehicle
  where vehicle.deleted_at is null
    and vehicle.approval_status = 'approved'
    and p_dropoff_at > p_pickup_at
    and (p_district is null or vehicle.district = p_district)
    and (p_location is null or vehicle.location = p_location)
    and not exists (
      select 1 from public.bookings as booking
      where booking.vehicle_id = vehicle.id
        and booking.status in ('pending', 'confirmed', 'active')
        and tstzrange(booking.pickup_at, booking.dropoff_at, '[)')
          && tstzrange(p_pickup_at, p_dropoff_at, '[)')
    )
  order by vehicle.price_per_day, vehicle.created_at desc;
$$;

create or replace function public.create_booking(
  p_vehicle_id uuid,
  p_pickup_at timestamptz,
  p_dropoff_at timestamptz,
  p_pickup_district text,
  p_pickup_location text,
  p_dropoff_location text,
  p_contact_email text,
  p_contact_phone text,
  p_contact_address text,
  p_payment_method text,
  p_coupon_code text default null
)
returns public.bookings
language plpgsql
security definer
set search_path = ''
as $$
declare
  selected_vehicle public.vehicles;
  created_booking public.bookings;
  number_of_days integer;
  pickup_support_fee numeric(12, 2) := 10000;
  booking_discount numeric(12, 2) := 0;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  if public.current_app_role() <> 'customer' then
    raise exception 'Only customers can create bookings' using errcode = '42501';
  end if;
  if p_dropoff_at <= p_pickup_at then
    raise exception 'Drop-off must be later than pickup' using errcode = '22007';
  end if;

  select * into selected_vehicle from public.vehicles
  where id = p_vehicle_id and deleted_at is null and approval_status = 'approved'
  for update;

  if selected_vehicle.id is null then
    raise exception 'Vehicle is not available' using errcode = 'P0002';
  end if;

  number_of_days := greatest(
    1,
    ceil(extract(epoch from (p_dropoff_at - p_pickup_at)) / 86400.0)::integer
  );
  booking_discount := case when upper(coalesce(p_coupon_code, '')) = 'KARIBU10000' then 10000 else 0 end;

  insert into public.bookings (
    vehicle_id, customer_id, pickup_at, dropoff_at, pickup_district,
    pickup_location, dropoff_location, contact_email, contact_phone,
    contact_address, rental_days, daily_price, delivery_fee, discount, total_price
  ) values (
    selected_vehicle.id, (select auth.uid()), p_pickup_at, p_dropoff_at,
    p_pickup_district, p_pickup_location, p_dropoff_location, p_contact_email,
    p_contact_phone, p_contact_address, number_of_days,
    selected_vehicle.price_per_day, pickup_support_fee,
    booking_discount,
    greatest(0, selected_vehicle.price_per_day * number_of_days + pickup_support_fee - booking_discount)
  ) returning * into created_booking;

  insert into public.payments (booking_id, provider, amount)
  values (created_booking.id, p_payment_method, created_booking.total_price);

  insert into public.booking_status_history (booking_id, to_status, changed_by)
  values (created_booking.id, created_booking.status, (select auth.uid()));
  return created_booking;
exception
  when exclusion_violation then
    raise exception 'Vehicle is already booked for the selected dates' using errcode = '23P01';
end;
$$;

create or replace function public.set_booking_status(
  p_booking_id uuid,
  p_status public.booking_status
)
returns public.bookings
language plpgsql
security definer
set search_path = ''
as $$
declare
  existing_booking public.bookings;
  updated_booking public.bookings;
  caller_role public.app_role;
begin
  caller_role := public.current_app_role();
  select * into existing_booking from public.bookings where id = p_booking_id for update;
  if existing_booking.id is null then
    raise exception 'Booking not found' using errcode = 'P0002';
  end if;
  if caller_role <> 'admin' and not exists (
    select 1 from public.vehicles
    where id = existing_booking.vehicle_id and owner_id = (select auth.uid())
  ) then
    raise exception 'Not allowed to update this booking' using errcode = '42501';
  end if;

  update public.bookings
  set status = p_status,
      cancelled_at = case when p_status = 'cancelled' then now() else cancelled_at end
  where id = p_booking_id
  returning * into updated_booking;

  insert into public.booking_status_history (booking_id, from_status, to_status, changed_by)
  values (updated_booking.id, existing_booking.status, updated_booking.status, (select auth.uid()));
  return updated_booking;
end;
$$;

create or replace function public.cancel_own_booking(p_booking_id uuid)
returns public.bookings
language plpgsql
security definer
set search_path = ''
as $$
declare
  existing_booking public.bookings;
  updated_booking public.bookings;
begin
  select * into existing_booking from public.bookings
  where id = p_booking_id and customer_id = (select auth.uid()) for update;
  if existing_booking.id is null then
    raise exception 'Booking not found' using errcode = 'P0002';
  end if;
  if existing_booking.status not in ('pending', 'confirmed') then
    raise exception 'This booking can no longer be cancelled' using errcode = 'P0001';
  end if;

  update public.bookings set status = 'cancelled', cancelled_at = now()
  where id = p_booking_id returning * into updated_booking;
  insert into public.booking_status_history (booking_id, from_status, to_status, changed_by)
  values (updated_booking.id, existing_booking.status, 'cancelled', (select auth.uid()));
  return updated_booking;
end;
$$;

create or replace function public.review_vehicle(
  p_vehicle_id uuid,
  p_approval_status public.vehicle_approval_status,
  p_rejection_reason text default null
)
returns public.vehicles
language plpgsql
security definer
set search_path = ''
as $$
declare
  result public.vehicles;
begin
  if not public.is_admin() then
    raise exception 'Admin access required' using errcode = '42501';
  end if;
  if p_approval_status = 'pending' then
    raise exception 'Review must approve or reject a vehicle' using errcode = '22023';
  end if;

  update public.vehicles
  set approval_status = p_approval_status,
      rejection_reason = case when p_approval_status = 'rejected' then p_rejection_reason else null end
  where id = p_vehicle_id returning * into result;
  return result;
end;
$$;

