create extension if not exists btree_gist with schema extensions;

create type public.app_role as enum ('customer', 'vendor', 'admin');
create type public.vehicle_approval_status as enum ('pending', 'approved', 'rejected');
create type public.booking_status as enum (
  'pending', 'confirmed', 'active', 'completed', 'cancelled', 'rejected'
);
create type public.payment_status as enum ('pending', 'paid', 'failed', 'refunded');

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null check (char_length(username) between 2 and 80),
  phone_number text,
  address text,
  avatar_url text,
  role public.app_role not null default 'customer',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.locations (
  id bigint generated by default as identity primary key,
  district text not null,
  name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (district, name)
);

create table public.vehicles (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid references public.profiles (id) on delete set null,
  registration_number text not null unique,
  company text not null,
  name text not null,
  model text not null,
  title text,
  description text,
  year_made integer check (year_made between 1950 and 2100),
  fuel_type text check (fuel_type in ('petrol', 'diesel', 'electric', 'hybrid')),
  seats smallint check (seats between 1 and 60),
  transmission text check (transmission in ('manual', 'automatic')),
  car_type text,
  price_per_day numeric(12, 2) not null check (price_per_day >= 0),
  base_package text,
  district text not null,
  location text not null,
  rating numeric(2, 1) check (rating between 0 and 5),
  insurance_expires_on date,
  registration_expires_on date,
  pollution_certificate_expires_on date,
  approval_status public.vehicle_approval_status not null default 'pending',
  rejection_reason text,
  is_admin_added boolean not null default false,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.vehicle_images (
  id bigint generated by default as identity primary key,
  vehicle_id uuid not null references public.vehicles (id) on delete cascade,
  storage_path text,
  public_url text,
  position smallint not null default 0,
  created_at timestamptz not null default now(),
  check (storage_path is not null or public_url is not null),
  unique (vehicle_id, position)
);

create table public.bookings (
  id uuid primary key default gen_random_uuid(),
  vehicle_id uuid not null references public.vehicles (id) on delete restrict,
  customer_id uuid references public.profiles (id) on delete set null,
  pickup_at timestamptz not null,
  dropoff_at timestamptz not null,
  pickup_district text not null,
  pickup_location text not null,
  dropoff_location text not null,
  contact_email text not null,
  contact_phone text not null,
  contact_address text not null,
  rental_days integer not null check (rental_days > 0),
  daily_price numeric(12, 2) not null check (daily_price >= 0),
  delivery_fee numeric(12, 2) not null default 0 check (delivery_fee >= 0),
  discount numeric(12, 2) not null default 0 check (discount >= 0),
  total_price numeric(12, 2) not null check (total_price >= 0),
  currency char(3) not null default 'TZS',
  status public.booking_status not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  cancelled_at timestamptz,
  check (dropoff_at > pickup_at),
  constraint bookings_no_overlapping_vehicle_reservations
    exclude using gist (
      vehicle_id with =,
      tstzrange(pickup_at, dropoff_at, '[)') with &&
    ) where (status in ('pending', 'confirmed', 'active'))
);

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  booking_id uuid not null references public.bookings (id) on delete restrict,
  provider text not null,
  provider_reference text,
  amount numeric(12, 2) not null check (amount >= 0),
  currency char(3) not null default 'TZS',
  status public.payment_status not null default 'pending',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider, provider_reference)
);

create table public.booking_status_history (
  id bigint generated by default as identity primary key,
  booking_id uuid not null references public.bookings (id) on delete cascade,
  from_status public.booking_status,
  to_status public.booking_status not null,
  changed_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

